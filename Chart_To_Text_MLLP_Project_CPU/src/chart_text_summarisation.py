def extract_ocr_with_positions(pil_image):
  image_array = np.array(pil_image)

  detections = ocr_reader.readtext(
      image_array,
      detail = 1
  )

  results = []

  for bbox, text, confidence in detections:
    if confidence >= 0.25:

      x_coordinates = [
          point[0] for point in bbox
      ]
      y_coordinates = [
          point[1] for point in bbox
      ]

      result = {
          "text": text,
          "confidence": round(
              float(confidence), 3
          ),
          "x": round(float(min(x_coordinates)),1),
          "y": round(float(min(y_coordinates)), 1),

      }
      results.append(result)

  return results

