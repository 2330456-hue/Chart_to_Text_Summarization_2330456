# Generating the natural language summary
def generate_nlp_summary(evidence_text):

  prompt = (
      "Summarize this chart data in 2 short sentences."
      "Mention the highest value and the lowest value."
      "Use only the data provided.\n\n"
      f"{evidence_text}\n\n"
      "Write the summary:"
  )

  inputs = tokenizer(
      prompt,
      return_tensors = "pt",
      truncation = True,
      max_length = 512
  )

  inputs = {key: value.to("cpu")
      for key, value in inputs.items()}

  with torch.no_grad():

    outputs = model.generate(
        **inputs,
        max_new_tokens = 100,
        min_new_tokens = 10,
        num_beams = 4,
        do_sample = False,
        early_stopping = True
    )

  summary = tokenizer.decode(
      outputs[0],
      skip_special_tokens = True
  ).strip()

  return summary

