# Function to Identify numbers and labels
def extract_numbers_and_labels(text_list):

  numbers = []
  labels = []

  for text in text_list:

    cleaned = text.replace(",","").strip()

    number_match = re.fullmatch(
        r"-?\d+(?:\.\d+)?%?" ,
        cleaned
    )

    if number_match:

      numeric_text = cleaned.replace("%","")

      try:
        numbers.append(
            float(numeric_text)
        )

      except ValueError:
         pass
    else:
      labels.append(text)

  return labels, numbers

