def analyze_chart_data(data):

    if not data:
        return None

    categories = list(data.keys())
    values = list(data.values())

    max_value = max(values)
    min_value = min(values)

    max_index = values.index(max_value)
    min_index = values.index(min_value)

    analysis = {
        "total_categories": len(categories),

        "highest_category":
            categories[max_index],

        "highest_value":
            max_value,

        "lowest_category":
            categories[min_index],

        "lowest_value":
            min_value,

        "first_category":
            categories[0],

        "first_value":
            values[0],

        "last_category":
            categories[-1],

        "last_value":
            values[-1]
    }

    if len(values) >= 2:

        analysis["overall_change"] = (
            values[-1] - values[0]
        )

    return analysis

